-- =====================================================================
-- V1: โครงสร้างฐานข้อมูล 7 ตาราง (PostgreSQL)
--   users 1---1 user_profiles
--   categories 1---N costumes
--   users 1---N rentals N---1 costumes
--   rentals 1---1 payments
--   rentals 1---1 shipments
-- =====================================================================

CREATE TABLE users (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username  VARCHAR(50)  NOT NULL,
    password  VARCHAR(255) NOT NULL,
    email     VARCHAR(120),
    role      VARCHAR(20)  NOT NULL DEFAULT 'USER',
    CONSTRAINT uk_users_username UNIQUE (username),
    CONSTRAINT uk_users_email    UNIQUE (email),
    CONSTRAINT ck_users_role     CHECK (role IN ('USER', 'ADMIN'))
);

CREATE TABLE user_profiles (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT NOT NULL,
    full_name    VARCHAR(120),
    phone        VARCHAR(20),
    address_line TEXT,
    sub_district VARCHAR(80),
    district     VARCHAR(80),
    province     VARCHAR(80),
    postal_code  VARCHAR(10),
    -- UNIQUE บังคับให้เป็น One-to-One จริงที่ระดับฐานข้อมูล
    CONSTRAINT uk_user_profiles_user UNIQUE (user_id),
    -- ลบ user แล้วโปรไฟล์ต้องหายตาม
    CONSTRAINT fk_user_profiles_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE TABLE categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(80) NOT NULL,
    description VARCHAR(255),
    CONSTRAINT uk_categories_name UNIQUE (name)
);

CREATE TABLE costumes (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(150)   NOT NULL,
    category_id   BIGINT,
    price_per_day NUMERIC(10, 2) NOT NULL,
    description   TEXT,
    status        VARCHAR(30)    NOT NULL DEFAULT 'AVAILABLE',
    image_url     VARCHAR(255),
    CONSTRAINT ck_costumes_price  CHECK (price_per_day >= 0),
    CONSTRAINT ck_costumes_status CHECK (status IN ('AVAILABLE', 'RESERVED', 'WAITING_RETURN', 'LAUNDRY', 'UNAVAILABLE')),
    -- ไม่ใส่ ON DELETE CASCADE: ลบหมวดหมู่ที่ยังมีชุดอยู่ต้องถูกปฏิเสธ (ชุดห้ามหายตามหมวด)
    CONSTRAINT fk_costumes_category FOREIGN KEY (category_id) REFERENCES categories (id)
);

CREATE TABLE rentals (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT         NOT NULL,
    costume_id     BIGINT         NOT NULL,
    start_date     DATE           NOT NULL,
    end_date       DATE           NOT NULL,
    total_days     INTEGER        NOT NULL,
    total_price    NUMERIC(10, 2) NOT NULL DEFAULT 0,
    deposit_amount NUMERIC(10, 2) NOT NULL DEFAULT 0,
    status         VARCHAR(30)    NOT NULL DEFAULT 'PENDING_PAYMENT',
    created_at     TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_rentals_dates  CHECK (end_date >= start_date),
    CONSTRAINT ck_rentals_status CHECK (status IN ('PENDING_PAYMENT', 'PAID', 'SHIPPED', 'IN_USE', 'RETURNED', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT fk_rentals_user    FOREIGN KEY (user_id)    REFERENCES users (id),
    CONSTRAINT fk_rentals_costume FOREIGN KEY (costume_id) REFERENCES costumes (id)
);

CREATE TABLE payments (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rental_id      BIGINT         NOT NULL,
    amount         NUMERIC(10, 2) NOT NULL,
    payment_type   VARCHAR(30),
    payment_method VARCHAR(30),
    slip_image_url VARCHAR(255),
    payment_date   TIMESTAMP,
    status         VARCHAR(20)    NOT NULL DEFAULT 'PENDING',
    CONSTRAINT uk_payments_rental UNIQUE (rental_id),
    CONSTRAINT ck_payments_status CHECK (status IN ('PENDING', 'VERIFIED', 'REJECTED')),
    CONSTRAINT fk_payments_rental FOREIGN KEY (rental_id) REFERENCES rentals (id) ON DELETE CASCADE
);

CREATE TABLE shipments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rental_id   BIGINT NOT NULL,
    courier     VARCHAR(80),
    tracking_no VARCHAR(80),
    shipped_at  TIMESTAMP,
    CONSTRAINT uk_shipments_rental UNIQUE (rental_id),
    CONSTRAINT fk_shipments_rental FOREIGN KEY (rental_id) REFERENCES rentals (id) ON DELETE CASCADE
);

-- Index สำหรับ query ที่ใช้บ่อย (UNIQUE ข้างบนสร้าง index ให้อัตโนมัติอยู่แล้ว)
CREATE INDEX idx_rentals_user_id     ON rentals (user_id);
CREATE INDEX idx_rentals_costume_id  ON rentals (costume_id);
CREATE INDEX idx_rentals_status      ON rentals (status);
CREATE INDEX idx_costumes_category_id ON costumes (category_id);
CREATE INDEX idx_costumes_status     ON costumes (status);
